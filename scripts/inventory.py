#!/usr/bin/env python3
"""Inventory of the CSS custom properties that Gitea reads, extracted from a real instance.

    python3 scripts/inventory.py --fetch http://127.0.0.1:3000 DIR   # download the built assets of a running Gitea into DIR
    python3 scripts/inventory.py --extract DIR                        # DIR -> src/gitea-inventory.json
    python3 scripts/inventory.py --check DIR                          # fail if src/gitea-inventory.json differs from DIR

DIR holds the built frontend of one Gitea release: `index.<hash>.css`, `theme-gitea-auto.<hash>.css` (it carries the
light and dark defaults of the built-in themes), `index.<hash>.js` and the lazy chunks in `js/`.
`--fetch` reads them from the page of any Gitea of that release (a throwaway container is enough).

The inventory states facts only: which variables the built-in themes declare (with their default values in both
modes), how many CSS declarations and which JavaScript chunks consume each one, and the custom properties that live
outside the themes (fonts, radii). The decision of what each one becomes is in scripts/build.py. Python 3.10+, standard
library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INV = ROOT / "src" / "gitea-inventory.json"


def _walk(css: str, out: dict[str, list[tuple[str, str]]]) -> None:
    """Flatten nested @media/@supports blocks and record, per var(--x), the (selector, property) that reads it."""
    pos, n = 0, len(css)
    while pos < n:
        j = css.find("{", pos)
        if j < 0:
            break
        sel = css[pos:j].strip()
        depth, k = 1, j + 1
        while depth and k < n:
            depth += (css[k] == "{") - (css[k] == "}")
            k += 1
        body = css[j + 1:k - 1]
        if sel.startswith(("@media", "@supports", "@layer")):
            _walk(body, out)
        elif not sel.startswith("@"):
            for decl in re.split(r";(?![^()]*\))", body):
                m = re.match(r"\s*([\w-]+)\s*:(.*)", decl, re.S)
                if m:
                    for v in re.findall(r"var\((--[\w-]+)", m.group(2)):
                        out.setdefault(v, []).append((sel, m.group(1)))
        pos = k


def _decls(block: str) -> dict[str, str]:
    return {k: v.strip() for k, v in re.findall(r"(--[\w-]+|accent-color|color-scheme)\s*:\s*([^;}]+)", block)}


def one(dirpath: Path, pattern: str) -> Path:
    found = sorted(dirpath.glob(pattern))
    if len(found) != 1:
        sys.exit(f"error: expected exactly one {pattern} in {dirpath}, found {len(found)}")
    return found[0]


def extract(dirpath: Path) -> dict:
    auto = one(dirpath, "theme-gitea-auto.*.css").read_text()
    index = one(dirpath, "index.*.css").read_text()
    split = auto.index("@media(prefers-color-scheme:dark)")
    blocks = {}
    for mode, chunk in (("light", auto[:split]), ("dark", auto[split:])):
        m = re.search(r":root\{(.*?)\}", chunk, re.S)
        if not m:
            sys.exit(f"error: no :root block for {mode} in the auto theme")
        blocks[mode] = _decls(m.group(1))
    light, dark = blocks["light"], blocks["dark"]
    if set(light) != set(dark):
        sys.exit("error: light and dark themes declare different variables")

    uses: dict[str, list[tuple[str, str]]] = {}
    _walk(index, uses)
    js_files = [one(dirpath, "index.*.js")] + sorted((dirpath / "js").glob("*.js"))
    js_reads: dict[str, list[str]] = {}
    for f in js_files:
        for name in set(re.findall(r"--[a-z][a-z0-9-]+", f.read_text(errors="replace"))):
            js_reads.setdefault(name, []).append(f.name.split(".")[0])

    theme_vars = []
    for name in sorted(light, key=lambda s: list(light).index(s)):
        theme_vars.append({
            "name": name,
            "dark": dark[name],
            "light": light[name],
            "css_uses": len(uses.get(name, [])),
            "js": sorted(set(js_reads.get(name, []))),
        })

    other = {}
    for m in re.finditer(r"(?<![\w-])(--[a-zA-Z0-9-]+)\s*:\s*([^;}]{0,300})", index):
        name = m.group(1)
        if name in light or name.startswith(("--tw-", "--fa-")):
            continue
        other.setdefault(name, m.group(2).strip())
    other_vars = [{"name": k, "value": v[:160], "css_uses": len(uses.get(k, []))} for k, v in sorted(other.items())]

    css_used_colors = sorted(n for n in uses if n in light)
    return {
        "gitea": "28.2.0",
        "note": "Generated by scripts/inventory.py from the built frontend of gitea/gitea:28.2.0. Do not edit by hand.",
        "theme_vars": theme_vars,
        "other_vars": other_vars,
        "counts": {
            "theme_vars": len(theme_vars),
            "read_by_css": len(css_used_colors),
            "read_by_js_only": len([v for v in theme_vars if v["css_uses"] == 0 and v["js"]]),
            "no_reader_found": len([v for v in theme_vars if v["css_uses"] == 0 and not v["js"] and v["name"].startswith("--color")]),
        },
    }


def fetch(base: str, dest: Path) -> None:
    base = base.rstrip("/")
    (dest / "js").mkdir(parents=True, exist_ok=True)

    def get(path: str) -> bytes:
        with urllib.request.urlopen(base + path, timeout=60) as r:
            return r.read()

    page = get("/user/login").decode()
    links = re.findall(r'(?:href|src)="[^"]*?(/assets/(?:css|js)/[^"]+)"', page)
    want = [l for l in links if re.search(r"/(index|theme-gitea-auto)\.", l)]
    if len(want) < 3:
        sys.exit(f"error: did not find the entry assets in the page (found {want})")
    for l in want:
        (dest / Path(l).name).write_bytes(get(l))
    entry_js = one(dest, "index.*.js").read_text()
    for name in sorted(set(re.findall(r"\./([A-Za-z0-9._-]+\.[A-Za-z0-9_-]{8}\.js)", entry_js))):
        (dest / "js" / name).write_bytes(get("/assets/js/" + name))
    print(f"ok: fetched {len(list(dest.glob('*.*')))} entry files and {len(list((dest / 'js').glob('*.js')))} chunks into {dest}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fetch", nargs=2, metavar=("URL", "DIR"))
    ap.add_argument("--extract", metavar="DIR")
    ap.add_argument("--check", metavar="DIR")
    a = ap.parse_args()
    if a.fetch:
        fetch(a.fetch[0], Path(a.fetch[1]))
    elif a.extract:
        INV.write_text(json.dumps(extract(Path(a.extract)), indent=1, ensure_ascii=False) + "\n")
        print(f"wrote {INV.relative_to(ROOT)}")
    elif a.check:
        want = json.dumps(extract(Path(a.check)), indent=1, ensure_ascii=False) + "\n"
        if INV.read_text() != want:
            sys.exit("error: src/gitea-inventory.json differs from the assets in " + a.check)
        print(f"ok: inventory matches {a.check}")
    else:
        ap.print_help()


if __name__ == "__main__":
    main()
